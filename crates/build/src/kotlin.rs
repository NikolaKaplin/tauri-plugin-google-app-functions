//! Renders the Kotlin `@AppFunctionServiceEntryPoint` service that forwards every call to Rust.

use std::fmt::Write;

use crate::{
  docs::render_kdoc,
  parse::{Function, KType, Model, Primitive, Serializable},
};

/// Package of the generated Kotlin code. The plugin's AndroidManifest.xml registers
/// `$PACKAGE.$SERVICE_NAME`, so these must stay in sync with it.
pub const PACKAGE: &str = "com.plugin.google_app_functions.generated";
pub const SERVICE_NAME: &str = "TauriAppFunctionService";
/// Asset name (without `.xml`) KSP writes the AppFunctions schema to; referenced by the manifest.
pub const XML_FILE_NAME: &str = "tauri_app_functions";

const KEYWORDS: &[&str] = &[
  "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
  "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true",
  "try", "typealias", "typeof", "val", "var", "when", "while",
];

fn ident(name: &str) -> String {
  if KEYWORDS.contains(&name) { format!("`{name}`") } else { name.to_owned() }
}

fn string_literal(value: &str) -> String {
  let mut out = String::from("\"");
  for ch in value.chars() {
    match ch {
      '"' => out.push_str("\\\""),
      '\\' => out.push_str("\\\\"),
      '$' => out.push_str("\\$"),
      '\n' => out.push_str("\\n"),
      c => out.push(c),
    }
  }
  out.push('"');
  out
}

fn primitive_name(p: Primitive) -> &'static str {
  match p {
    Primitive::Boolean => "Boolean",
    Primitive::Int => "Int",
    Primitive::Long => "Long",
    Primitive::Float => "Float",
    Primitive::Double => "Double",
  }
}

fn kotlin_type(ty: &KType) -> String {
  match ty {
    KType::Primitive(p) => primitive_name(*p).to_owned(),
    KType::String => "String".to_owned(),
    KType::Nullable(inner) => format!("{}?", kotlin_type(inner)),
    KType::List(inner) => format!("List<{}>", kotlin_type(inner)),
    KType::PrimitiveArray(p) => format!("{}Array", primitive_name(*p)),
    KType::Custom(name) => name.clone(),
    KType::Unit => "Unit".to_owned(),
  }
}

/// Kotlin expression converting `expr` of type `ty` into a value `JSONObject.put` accepts.
fn encode(ty: &KType, expr: &str, depth: usize) -> String {
  let var = format!("v{depth}");
  match ty {
    KType::Primitive(_) | KType::String | KType::Unit => expr.to_owned(),
    KType::Nullable(inner) => format!(
      "J.encodeNullable({expr}) {{ {var} -> {} }}",
      encode(inner, &var, depth + 1)
    ),
    KType::List(inner) => format!(
      "J.encodeList({expr}) {{ {var} -> {} }}",
      encode(inner, &var, depth + 1)
    ),
    KType::PrimitiveArray(_) => format!("J.encodeArray({expr})"),
    KType::Custom(name) => format!("encode{name}({expr})"),
  }
}

/// Kotlin expression converting the JSON value `expr` (`Any?`) into `ty`.
fn decode(ty: &KType, expr: &str, depth: usize) -> String {
  let var = format!("v{depth}");
  match ty {
    KType::Primitive(p) => format!("J.{}({expr})", primitive_name(*p).to_ascii_lowercase()),
    KType::String => format!("J.string({expr})"),
    KType::Nullable(inner) => format!(
      "J.nullable({expr}) {{ {var} -> {} }}",
      decode(inner, &var, depth + 1)
    ),
    KType::List(inner) => format!(
      "J.list({expr}) {{ {var} -> {} }}",
      decode(inner, &var, depth + 1)
    ),
    KType::PrimitiveArray(p) => format!("J.{}Array({expr})", primitive_name(*p).to_ascii_lowercase()),
    KType::Custom(name) => format!("decode{name}({expr})"),
    KType::Unit => expr.to_owned(),
  }
}

pub fn render(model: &Model, library: &str) -> String {
  let mut out = String::new();
  out.push_str(
    "// THIS FILE IS AUTO-GENERATED BY tauri-plugin-google-app-functions-build. DO NOT EDIT.\n",
  );
  out.push_str("// Regenerated from the #[app_function] items of the Rust crate on every build.\n\n");
  out.push_str("@file:Suppress(\"unused\", \"RedundantVisibilityModifier\", \"UNUSED_ANONYMOUS_PARAMETER\")\n\n");
  let _ = writeln!(out, "package {PACKAGE}\n");
  out.push_str(
    "import androidx.annotation.RequiresApi\n\
     import androidx.appfunctions.AppFunction\n\
     import androidx.appfunctions.AppFunctionSerializable\n\
     import androidx.appfunctions.AppFunctionService\n\
     import androidx.appfunctions.AppFunctionServiceEntryPoint\n\
     import com.plugin.google_app_functions.AppFunctionsBridge\n\
     import com.plugin.google_app_functions.AppFunctionsJson as J\n\
     import org.json.JSONObject\n\n",
  );
  let _ = writeln!(out, "private const val LIBRARY = {}\n", string_literal(library));

  for serializable in &model.serializables {
    render_serializable(&mut out, serializable);
  }

  out.push_str("@RequiresApi(36)\n");
  let _ = writeln!(
    out,
    "@AppFunctionServiceEntryPoint(\n    serviceName = \"{SERVICE_NAME}\",\n    appFunctionXmlFileName = \"{XML_FILE_NAME}\",\n)"
  );
  let _ = writeln!(out, "abstract class {SERVICE_NAME}Base : AppFunctionService() {{");
  for (i, function) in model.functions.iter().enumerate() {
    if i > 0 {
      out.push('\n');
    }
    render_function(&mut out, function);
  }
  out.push_str("}\n");
  out
}

fn render_serializable(out: &mut String, s: &Serializable) {
  out.push_str(&render_kdoc("", &s.docs.description, &[]));
  out.push_str("@AppFunctionSerializable(isDescribedByKDoc = true)\n");
  let _ = writeln!(out, "data class {}(", s.name);
  for field in &s.fields {
    out.push_str(&render_kdoc("    ", &field.docs.description, &[]));
    let _ = writeln!(out, "    val {}: {},", ident(&field.name), kotlin_type(&field.ty));
  }
  out.push_str(")\n\n");

  let _ = writeln!(
    out,
    "private fun encode{name}(value: {name}): JSONObject = JSONObject().apply {{",
    name = s.name
  );
  for field in &s.fields {
    let _ = writeln!(
      out,
      "    put({}, {})",
      string_literal(&field.name),
      encode(&field.ty, &format!("value.{}", ident(&field.name)), 1)
    );
  }
  out.push_str("}\n\n");

  let _ = writeln!(out, "private fun decode{name}(json: Any?): {name} {{", name = s.name);
  out.push_str("    val o = J.obj(json)\n");
  let _ = writeln!(out, "    return {}(", s.name);
  for field in &s.fields {
    let _ = writeln!(
      out,
      "        {} = {},",
      ident(&field.name),
      decode(&field.ty, &format!("o.opt({})", string_literal(&field.name)), 1)
    );
  }
  out.push_str("    )\n}\n\n");
}

fn render_function(out: &mut String, f: &Function) {
  let mut tags = Vec::new();
  for param in &f.params {
    if let Some(description) = f.docs.param(&param.rust_name) {
      tags.push(format!("@param {} {description}", param.name));
    }
  }
  if let Some(returns) = &f.docs.returns {
    tags.push(format!("@return {returns}"));
  }
  out.push_str(&render_kdoc("    ", &f.docs.description, &tags));
  out.push_str("    @AppFunction(isDescribedByKDoc = true)\n");

  let params = f
    .params
    .iter()
    .map(|p| {
      let default = if matches!(p.ty, KType::Nullable(_)) { " = null" } else { "" };
      format!("{}: {}{default}", ident(&p.name), kotlin_type(&p.ty))
    })
    .collect::<Vec<_>>()
    .join(", ");
  let return_type = match &f.output {
    KType::Unit => String::new(),
    ty => format!(": {}", kotlin_type(ty)),
  };
  let _ = writeln!(out, "    suspend fun {}({params}){return_type} {{", ident(&f.kotlin_name));
  out.push_str("        val args = JSONObject()\n");
  for p in &f.params {
    let _ = writeln!(
      out,
      "        args.put({}, {})",
      string_literal(&p.name),
      encode(&p.ty, &ident(&p.name), 1)
    );
  }
  let call = format!(
    "AppFunctionsBridge.call(LIBRARY, {}, args)",
    string_literal(&f.rust_name)
  );
  match &f.output {
    KType::Unit => {
      let _ = writeln!(out, "        {call}");
    }
    ty => {
      let _ = writeln!(out, "        return {}", decode(ty, &call, 1));
    }
  }
  out.push_str("    }\n");
}

/// `res/xml` document holding the app description agents read before choosing a function.
pub fn render_app_metadata(description: &str) -> String {
  let escaped = description
    .replace('&', "&amp;")
    .replace('"', "&quot;")
    .replace('<', "&lt;")
    .replace('>', "&gt;")
    .replace('\n', "&#10;");
  format!(
    "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n\
     <!-- THIS FILE IS AUTO-GENERATED BY tauri-plugin-google-app-functions-build. DO NOT EDIT. -->\n\
     <AppFunctionAppMetadata xmlns:appfn=\"http://schemas.android.com/apk/androidx.appfunctions\"\n    \
     appfn:description=\"{escaped}\" />\n"
  )
}
